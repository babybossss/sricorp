def sheet(wb, name, title, note, columns, examples, widths=None):
    """columns: list of (header, required, hint)"""
    ws = wb.create_sheet(name)
    ws.sheet_view.showGridLines = False

    ws["A1"] = title
    ws["A1"].font = TITLE_FONT
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=max(len(columns), 4))

    ws["A2"] = note
    ws["A2"].font = NOTE_FONT
    ws["A2"].fill = NOTE_FILL
    ws["A2"].alignment = Alignment(wrap_text=True, vertical="center")
    ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=max(len(columns), 4))
    ws.row_dimensions[2].height = 32

    # หัวคอลัมน์ที่แถว 4 · คำใบ้ที่แถว 5 · ตัวอย่างแถว 6+
    for i, (header, required, hint) in enumerate(columns, start=1):
        c = ws.cell(row=4, column=i, value=header + (" *" if required else ""))
        c.font = HEAD_FONT
        c.fill = REQ_FILL if required else OPT_FILL
        c.border = BORDER
        c.alignment = Alignment(wrap_text=True, vertical="center")

        h = ws.cell(row=5, column=i, value=hint)
        h.font = NOTE_FONT
        h.alignment = Alignment(wrap_text=True, vertical="top")
        h.border = BORDER

        ws.column_dimensions[get_column_letter(i)].width = (widths or {}).get(header, 22)

    ws.row_dimensions[4].height = 30
    ws.row_dimensions[5].height = 30

    for r, row in enumerate(examples, start=6):
        for i, v in enumerate(row, start=1):
            c = ws.cell(row=r, column=i, value=v)
            c.font = EX_FONT
            c.border = BORDER

    ws.freeze_panes = "A6"
    return ws


def dropdown(ws, col_letter, options, first=6, last=400):
    dv = DataValidation(type="list", formula1='"' + ",".join(options) + '"', allow_blank=True)
    dv.error = "เลือกจากรายการเท่านั้น"
    dv.errorTitle = "ค่าไม่ถูกต้อง"
    ws.add_data_validation(dv)
    dv.add(f"{col_letter}{first}:{col_letter}{last}")


