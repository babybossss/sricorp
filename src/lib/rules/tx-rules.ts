/**
 * บัญชีค้างรับทุกตัวที่เป็น **บัญชีพักของหมวดรายได้** (กระแสเงินสดดำเนินงาน)
 *
 * คำนวณจากตารางกฎ ไม่ใช่รายชื่อรหัสที่พิมพ์มือ — หมวดรายได้ตัวใหม่ที่ตั้งค้างได้
 * จะรองรับเองทันที และบัญชีที่ **ไม่ใช่** บัญชีพักของรายได้ (เช่น `1800`
 * ภาษีถูกหักรอเครดิต หรือ `1130` เงินให้กู้) จะไม่หลุดเข้ามา
 *
 * สำเนาฝั่ง DB อยู่ใน `fn_txn_type_can_withhold()` (อ่าน `accrual_coa_code`
 * ของแถวที่ `cr_coa_code` เป็นบัญชีรายได้และ `cf_group = 'operating'` ชุดเดียวกัน)
 */
let incomeAccrualAccountsCache: Set<string> | null = null;

function incomeAccrualAccounts(): Set<string> {
  if (!incomeAccrualAccountsCache) {
    const found = new Set<string>();
    for (const type of TX_TYPES) {
      for (const sub of type.subs) {
        if (sub.accrualCoa && sub.cashflow === "operating" && coa(sub.cr).type === "income") {
          found.add(sub.accrualCoa);
        }
      }
    }
    incomeAccrualAccountsCache = found;
  }
  return incomeAccrualAccountsCache;
}

/**
 * หมวดนี้ถูกหัก ณ ที่จ่ายได้ไหม — **คำนวณจากคู่บัญชี ไม่ใช่ธงที่พิมพ์มือรายหมวด**
 *
 * เงื่อนไขมาจากความหมายของเหตุการณ์ตรงๆ: มีคนจ่าย **เงินได้** ให้เรา
 * แล้วหักภาษีไว้ส่วนหนึ่งก่อนโอน จึงต้องเป็นหมวดที่
 *   1. เงินเข้า (`cash: "in"`) — ไม่มีใครหักภาษีจากเงินที่เราจ่ายออก
 *      (การที่ **เรา** เป็นผู้หักตอนจ่าย เป็นหนี้สินรอนำส่ง = คนละเรื่อง ยังไม่อยู่ในขอบเขต)
 *   2. ขาเดบิตเป็นเงินสด — ยอดที่เข้าบัญชีคือยอดสุทธิที่ต้องถูกแยกออกเป็นสองขา
 *   3. กระแสเงินสดหมวดดำเนินงาน — ให้ทางล้าง (`inv.wht_refund`) อยู่หมวดเดียวกัน
 *   4. ขาเครดิตเป็น **เงินได้** ซึ่งมีสองรูปในสมุดของเรา:
 *      (ก) **บัญชีรายได้** — ใบที่รับรู้รายได้พร้อมรับเงิน
 *      (ข) **บัญชีค้างรับของหมวดรายได้** — ใบรับชำระลูกหนี้ที่รับรู้รายได้
 *          ยอดเต็มไปแล้วตอนตั้งค้าง · ผู้จ่ายหักภาษีตอน **จ่ายเงินจริง**
 *          ซึ่งเป็นสิ่งที่เกิดทุกเดือน: ออกใบแจ้งหนี้ → ตั้งลูกหนี้ค่าเช่า →
 *          ผู้เช่าจ่ายแล้วหัก 5% · ก่อนจะมี (ข) เส้นทางนี้ **ลงไม่ได้ทุกทาง**
 *          (ตั้งค้างพร้อมหักภาษีก็ไม่ได้ · ตอนรับชำระก็ไม่ได้)
 *      การรับคืนเงินต้น/มัดจำ/การโอนเงินตัวเอง ไม่ใช่เงินได้ จึงยังไม่มีการหัก
 *
 * ทำแบบคำนวณเพราะหมวดรายได้ตัวใหม่ในอนาคตจะรองรับเองทันที
 * ธงที่ติ๊กรายหมวดคือของที่ **ลืมติ๊กได้** แล้วผู้ใช้จะกรอกยอดสุทธิเป็นรายได้แทน
 * ซึ่งเป็นข้อผิดที่ทั้งใบยังสมดุลและไม่มีอะไรฟ้อง
 *
 * สำเนาฝั่ง DB คือ `fn_txn_type_can_withhold()` ซึ่งอ่านฟิลด์ชุดเดียวกันจาก
 * `txn_types` และมีเทสต์ฝั่ง SQL (W1) เขียนเงื่อนไขซ้ำอย่างอิสระแล้วเทียบทุกแถว
 */
export function canWithholdTax(sub: SubCategory): boolean {
  if (!(sub.cash === "in" && sub.cashflow === "operating" && isCashAccount(sub.dr))) {
    return false;
  }
  if (coa(sub.cr).type === "income") return true;
  return incomeAccrualAccounts().has(sub.cr);
}

/** เหตุผลที่หมวดนี้ถูกหักภาษี ณ ที่จ่ายไม่ได้ — คำนวณที่เดียว เหมือน `accrualCheck()` */
export type WhtCheck = { ok: true; account: string } | { ok: false; why: string };

export function whtCheck(sub: SubCategory): WhtCheck {
  if (!canWithholdTax(sub)) {
    const reasons: string[] = [];
    if (sub.cash !== "in") reasons.push(`ทิศเงินเป็น "${cashDirectionLabel(sub.cash)}" ไม่ใช่เงินเข้า`);
    if (!isCashAccount(sub.dr)) reasons.push("ขาเดบิตไม่ใช่เงินสด จึงไม่มียอดสุทธิให้แยก");
    if (coa(sub.cr).type !== "income") {
      reasons.push(`ขาเครดิตเป็น ${coaLabel(sub.cr)} ซึ่งไม่ใช่บัญชีรายได้ — ภาษีหัก ณ ที่จ่ายหักจากเงินได้เท่านั้น`);
    }
    if (sub.cashflow !== "operating") reasons.push(`กระแสเงินสดเป็นหมวด${CF_TH[sub.cashflow]} ไม่ใช่ดำเนินงาน`);
    return {
      ok: false,
      why: reasons.join(" · "),
    };
  }
  return { ok: true, account: WHT_COA };
}

/** ทุกหมวดที่ถูกหักภาษี ณ ที่จ่ายได้ — ใช้ในเทสต์และหน้าตารางกฎ */
export function whtEligibleSubs(): SubCategory[] {
  return TX_TYPES.flatMap((t) => t.subs).filter(canWithholdTax);
}

/* ------------------------------------------------------------------ *
 * ตีราคาทรัพย์ (D-111 ข้อ 2)
 * ------------------------------------------------------------------ */

/**
 * หมวดนี้คือรายการตีราคาหรือไม่ — **ตัดสินจากคู่บัญชี** (แตะ 3400)
 *
 * มีสองตัวที่ตอบคำถามนี้โดยตั้งใจ และต้องตอบตรงกันเสมอ:
 *   - รูปของคู่บัญชี (ตัวนี้) ซึ่งฝั่ง SQL ตรวจได้จาก `txn_types.dr/cr_coa_code`
 *   - ธง `requires: "revaluation"` ซึ่งเป็นตัวที่ engine ใช้แยกสาขา
 * เทสต์บังคับให้สองตัวเท่ากันทุกหมวด — ถ้าต่างกัน แปลว่าด่านฝั่ง DB กับฝั่งโค้ด
 * กำลังคุมหมวดคนละชุด ซึ่งคือรูที่เงียบที่สุด
 */
export function isRevaluationSub(sub: SubCategory): boolean {
  return (
    isRevaluationSurplusAccount(sub.dr) || isRevaluationSurplusAccount(sub.cr)
  );
}

/* ------------------------------------------------------------------ *
 * ยอดยกมา (ตั้งต้นระบบ)
 * ------------------------------------------------------------------ */

/**
 * หมวดนี้คือ **ยอดยกมา** หรือไม่ — ตัดสินจากคู่บัญชี (แตะกำไรสะสม `3300`)
 * รูปเดียวกับ `isRevaluationSub()` (3400) และ `isFxTranslationSub()` (3410)
 * → ฝั่ง SQL ตรวจเรื่องเดียวกันได้จาก `txn_types.dr_coa_code/cr_coa_code`
 * และหมวดยอดยกมาตัวใหม่ในอนาคตถูกครอบเองทันที ไม่ต้องมารายชื่อรหัสหมวดเพิ่ม
 *
 * ใครใช้: `cashflow.ts` นับเงินสดของใบยอดยกมาเป็น **ยอดเงินสดต้นงวด**
 * ไม่ใช่กระแสเงินสดของงวด และไม่ใช่ความผิดปกติ
 */
export function isOpeningBalanceSub(sub: SubCategory): boolean {
  return sub.dr === RETAINED_EARNINGS_COA || sub.cr === RETAINED_EARNINGS_COA;
}

/* ------------------------------------------------------------------ *
 * อัตราแลกเปลี่ยนฝั่งเงินฝาก (FCD) — ลูกพี่ยืนยัน 25/10
 * ------------------------------------------------------------------ */

/**
 * หมวดนี้คือ **การแปลงค่าบัญชีเงินฝากสกุลต่างประเทศ** หรือไม่ — ตัดสินจากคู่บัญชี
 * (แตะ 3410) รูปเดียวกับ `isRevaluationSub()` ที่ตัดสินการตีราคาจาก 3400
 * ฝั่ง SQL ตรวจเรื่องเดียวกันได้จาก `txn_types.dr_coa_code/cr_coa_code`
 */
export function isFxTranslationSub(sub: SubCategory): boolean {
  return isFxTranslationAccount(sub.dr) || isFxTranslationAccount(sub.cr);
}

/**
 * หมวดนี้คือ **การแลกเงินตราเป็นบาทจริง** หรือไม่ — ตัดสินจากบัญชีกำไร/ขาดทุน
 * ที่หมวดนั้นประกาศไว้ (4330/5930) ซึ่งมีหมวดเดียวในระบบที่ประกาศได้
 */
export function isFxRealisingSub(sub: SubCategory): boolean {
  return sub.gainCoa === REALISED_FX_GAIN || sub.lossCoa === REALISED_FX_LOSS;
}

/**
 * หมวดนี้ทำให้ **ยอดบาทของเงินสดขยับเพราะอัตราแลกเปลี่ยน** หรือไม่
 *
 * ใช้โดย `cashflow.ts`: บรรทัดเงินสดของหมวดพวกนี้มี `cfCategory = "none"`
 * และ **สุทธิไม่เป็นศูนย์** ซึ่งปกติคือความผิดปกติ (`cashOutsideStatement`)
 * แต่สำหรับเรื่องค่าเงินมันคือ **บรรทัด "ผลกระทบของอัตราแลกเปลี่ยนต่อเงินสด"**
 * ของงบกระแสเงินสด (IAS 7.28) — ไม่ใช่กระแสเงินสดของงวด แต่ต้องอยู่ในการกระทบยอด
 * ไม่งั้นงบจะไม่กระทบยอดทุกเดือนที่ค่าเงินขยับ และ "ปิดเดือนไม่ได้" ทั้งที่ไม่มีอะไรผิด
 */
export function isFxCashSub(sub: SubCategory): boolean {
  return isFxTranslationSub(sub) || isFxRealisingSub(sub);
}

/** บัญชีทรัพย์ของหมวดตีราคานี้ — คือขาที่ไม่ใช่ส่วนเกินทุน */
export function revaluationAssetCoa(sub: SubCategory): string {
  if (!isRevaluationSub(sub)) {
    throw new Error(`หมวด ${sub.code} ไม่ใช่รายการตีราคา จึงไม่มีบัญชีทรัพย์ฝั่งตีราคา`);
  }
  return isRevaluationSurplusAccount(sub.dr) ? sub.cr : sub.dr;
}

/** ตีขึ้น = ทรัพย์อยู่ฝั่งเดบิต · ตีลง = ทรัพย์อยู่ฝั่งเครดิต */
export type RevaluationDirection = "up" | "down";

export function revaluationDirection(sub: SubCategory): RevaluationDirection {
  return isRevaluationSurplusAccount(sub.cr) ? "up" : "down";
}

/**
 * หมวดตีราคาของบัญชีทรัพย์นี้ ในทิศนี้ — **ถามตารางกฎ ไม่ใช่ประกอบรหัสหมวดเป็นสตริง**
 *
 * คืน `undefined` ถ้าไม่มี เพื่อให้ผู้เรียกปฏิเสธด้วยข้อความของตัวเอง
 * (ทรัพย์ที่ลงบัญชี 1500 อสังหาฯ ยังไม่มีหมวดตีราคา — ขอบเขตเฟสนี้คือฝั่งลงทุน)
 */
export function revaluationSubFor(
  assetCoa: string,
  direction: RevaluationDirection
): SubCategory | undefined {
  return TX_TYPES.flatMap((t) => t.subs).find(
    (s) =>
      isRevaluationSub(s) &&
      revaluationAssetCoa(s) === assetCoa &&
      revaluationDirection(s) === direction
  );
}

/** บัญชีทรัพย์ทุกตัวที่ตีราคาได้ในวันนี้ — ใช้ปฏิเสธแบบบอกทางเลือกที่มีจริง */
export function revaluableAssetCoas(): string[] {
  return [
    ...new Set(
      TX_TYPES.flatMap((t) => t.subs)
        .filter(isRevaluationSub)
        .map(revaluationAssetCoa)
    ),
  ];
}
