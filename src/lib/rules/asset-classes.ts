/**
 * **วิธีคิดต้นทุนของทรัพย์ชิ้นนี้** — ลูกพี่สั่งเอง 25/10 แล้วย้ำให้แคบลงอีกสองรอบ
 *
 * > "ห้ามเฉลี่ยต้นทุนในทุกทรัพย์สิน อสังหา และ อื่นๆ
 * >  **มีเฉพาะหุ้น หรือ คริปโต เท่านั้นที่เฉลี่ยในตลาดเท่านั้น หุ้นบริษัทนอกตลาดไม่เกี่ยว**"
 * > · ยืนยันเพิ่มภายหลัง: **ทองคำเฉลี่ยได้**
 *
 * ถัวเฉลี่ยได้ **สามอย่างเท่านั้น**: หุ้นในตลาดหลักทรัพย์ · คริปโต · ทองคำ
 * **ที่เหลือห้ามเฉลี่ยทั้งหมด** รวม **หุ้นบริษัทนอกตลาด** · ETF · กองทุน · พันธบัตร ·
 * อสังหาฯ ทุกชนิด · ที่ดิน · โครงการ · เงินให้กู้ · ขายฝาก · จำนอง · เงินมัดจำ
 *
 * ---------------------------------------------------------------------------
 * | ค่า | ความหมาย | ใช้กับ |
 * |---|---|---|
 * | `average` | ถัวเฉลี่ยถ่วงน้ำหนักทั้งกอง (D-112) | หุ้นในตลาด · คริปโต · ทองคำ |
 * | `specific_lot` | เก็บล็อตและ **ระบุล็อตที่ขาย** · ต้นทุนมาจากล็อตนั้นเอง ห้ามเฉลี่ยข้ามล็อต | หุ้นนอกตลาด · ETF · กองทุน · พันธบัตร |
 * | `whole_item` | **ทรัพย์ชิ้นเดียว แบ่งไม่ได้** · ตัดต้นทุนทั้งก้อนตอนขาย | อสังหาฯ · ที่ดิน · สัญญา · กิจการ · ของสะสม |
 * ---------------------------------------------------------------------------
 *
 * **ทำไมต้องมีสามค่า ไม่ใช่สอง** — `specific_lot` กับ `whole_item` ห้ามเฉลี่ย
 * เหมือนกัน แต่ **แบ่งขายได้ไม่เหมือนกัน**: หุ้นนอกตลาดซื้อสามครั้งเป็นสามล็อตจริง
 * และขายล็อตใดล็อตหนึ่งได้ (ต้นทุนมาจากล็อตนั้น) · ส่วนคอนโดหนึ่งห้องแบ่งขาย
 * 30% ไม่ได้เลย ถ้าใช้ค่าเดียวกันกับทั้งสอง ต้องเลือกระหว่าง
 * "ห้ามขายล็อตหุ้นนอกตลาด" (ปฏิเสธงานที่ถูก) หรือ "ยอมให้ขายคอนโดบางส่วน"
 * (ยอมตัวเลขที่ผิด) — ทั้งคู่ผิด จึงแยกเป็นสองค่า และ **ทั้งสองค่าไม่เฉลี่ย**
 * ไม่ได้ขัดกันเอง: คำถาม "เฉลี่ยได้ไหม" มีคำตอบเดียวคือ `=== "average"`
 *
 * **ค่าตั้งต้นคือ `whole_item`** (เข้มที่สุด) ทั้งฝั่งโค้ดและฝั่ง DB
 * (`asset_categories.cost_basis_mode default 'whole_item'`) — เผลอแล้วต้องได้
 * การ **ปฏิเสธเสียงดัง** ไม่ใช่การเฉลี่ยเงียบๆ · การอนุญาตให้เฉลี่ยต้องเป็น
 * การตั้งค่าอย่างตั้งใจในตารางอ้างอิง ไม่ใช่ผลข้างเคียงของการเว้นว่าง
 *
 * **ห้ามใช้รหัสบัญชีตัดสิน** — `1700` มีทั้งหุ้นในตลาดและหุ้นนอกตลาด ·
 * `1720` มีทั้งทองคำและสินทรัพย์ทางเลือกอื่น (นาฬิกา/งานศิลปะ) ที่เฉลี่ยไม่ได้
 * รหัสบัญชีจึงตัดสินแทนไม่ได้ทั้งสองฝั่ง และ **ห้ามอนุมานจาก `assets.ticker`**
 * ซึ่งเป็นช่องที่เว้นได้และกรอกผิดได้ (D-115)
 *
 * **ข้อยกเว้นโรงแรมของ D-112 ไม่ขัดกับเรื่องนี้** — "โรงแรมนับทั้งตึกเป็นชิ้นเดียว
 * ไม่แยกห้อง" เป็นเรื่องของจำนวนแถวใน `assets` ไม่ใช่เรื่องวิธีคิดต้นทุน
 * ตึกทั้งตึก = หนึ่งแถว = `whole_item` เหมือนคอนโดรายห้องที่เป็นหนึ่งแถวต่อห้อง
 */
