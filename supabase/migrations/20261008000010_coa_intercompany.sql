-- ------------------------------------------------------------
-- guard · ทุกรหัสที่ intercompany.ts อ้าง ต้องมีในผังบัญชี
--
-- จับ "ขาด" ไม่จับ "เพี้ยน" — รายการนี้พิมพ์มือจึงล้าสมัยได้ถ้า
-- `intercompany.ts` เพิ่มลักษณะใหม่ · ที่ถูกคือให้ `sync:rules` ครอบผังบัญชีด้วย
-- แล้วเลิกพึ่ง guard นี้ · จงใจให้ดังตอน migrate ไม่ใช่ตอนผู้ใช้กดบันทึก
-- ------------------------------------------------------------
do $$
declare v text;
begin
  select string_agg(c, ', ' order by c) into v
    from unnest(array['1310', '2310', '1710', '1200', '2200', '1100']) as c
   where not exists (select 1 from sri_os.chart_of_accounts a where a.code = c);

  if v is not null then
    raise exception
      'ผังบัญชีขาดรหัสที่ตารางกฎอ้างถึง: % — รายการข้ามผู้ถือจะถูกปฏิเสธตอนผู้ใช้กดบันทึก', v;
  end if;

  raise notice 'ผังบัญชี: รหัสที่รายการระหว่างกันใช้ มีครบแล้ว (% รหัสในผัง)',
    (select count(*) from sri_os.chart_of_accounts);
end $$;
