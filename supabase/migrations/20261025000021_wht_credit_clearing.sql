-- SRI OS · **ล้างเครดิตภาษีถูกหัก ณ ที่จ่ายได้จริง** (บัญชี 1800)
--
-- รูที่ปิด — **เจอจากการไล่ทุกหมวดในเทสต์ประตูร่าง (C-3)**
--   ระบบรับรู้ "ภาษีถูกหัก ณ ที่จ่าย" ได้ (เดบิต 1800) แต่ **ล้างไม่ได้เลย**
--   หมวด `inv.wht_refund` (เดบิตเงินสด / เครดิต 1800) ซึ่งเป็นทางล้างทางเดียว
--   ถูกด่าน gross-up ปฏิเสธ **ทุกใบ** เพราะด่านนั้นคิดยอด 1800 เป็น
--   **ยอดสุทธิ** (debit - credit) → ใบล้างได้ค่าติดลบ → เข้าเงื่อนไข
--   "มีบรรทัด 1800 แต่หมวดนี้ถูกหักภาษีไม่ได้" → ปฏิเสธ
--
--   ผลที่วัดได้: ยอด 1800 **โตขึ้นตลอดไป** · เครดิตภาษีที่ขอคืนได้จริง
--   ไม่มีทางหายออกจากงบดุล · และสินทรัพย์ภาษีในงบจะสูงกว่าความจริงเรื่อยๆ
--
--   **ด่านสองชั้นที่ขัดกันเอง**: guard ท้ายไฟล์ 20261025000001 ตรวจว่า
--   "ต้องมีหมวดที่ล้าง 1800 ได้" (บทเรียนข้อ 7) แต่ตรวจแค่ว่า **มีหมวดอยู่ใน
--   ตารางกฎ** ไม่ได้ตรวจว่า **ลงได้จริง** → ผ่านมาตลอดทั้งที่ของจริงลงไม่ได้
--   ไฟล์นี้จึงเพิ่ม guard ที่ตรวจ "ลงได้จริง" ด้วย (ไม่ใช่แค่ "มีชื่ออยู่")
--
-- สิ่งที่แก้
--   `fn_assert_wht_gross_for()` แยก **เดบิต** กับ **เครดิต** ของ 1800 ออกจากกัน
--     · เดบิต  = ถูกหักภาษีในใบนี้ → ตรวจสมการ gross-up ตามเดิมทุกข้อ
--     · เครดิต = ล้างเครดิตภาษี → ยอมเฉพาะหมวดที่ **ตารางกฎ** ระบุว่าเป็นทางล้าง
--                (ขาเดบิตเป็นเงินสด + ขาเครดิตเป็น 1800) · หมวดอื่นเครดิต 1800
--                ไม่ได้ ไม่งั้นสินทรัพย์ภาษีหายจากงบดุลโดยไม่มีเงินเข้ามาแทน
--     · ใบที่มีทั้งสองด้านพร้อมกัน = ปฏิเสธ (ต้องแยกใบ ไม่งั้นตรวจกับใบรับรองไม่ได้)
